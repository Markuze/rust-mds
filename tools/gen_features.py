#!/usr/bin/env python3
"""Generate crates/denc/src/features.rs from ceph.git src/include/ceph_features.h.

usage: gen_features.py <ceph_features.h> <out.rs>
"""
import re
import sys

src = open(sys.argv[1]).read()
inc = {"1": 0, "2": 1 << 57, "3": (1 << 57) | (1 << 28)}
defs = []
for m in re.finditer(r'DEFINE_CEPH_FEATURE(?:_DEPRECATED)?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\w+)', src):
    bit, incarnation, name = int(m.group(1)), m.group(2), m.group(3)
    defs.append((name, bit, incarnation))
names = {n: b for n, b, _ in defs}
allblk = re.search(r'#define CEPH_FEATURES_ALL\s*\\(.*?)\n\s*\n', src, re.S)
incs = {n: i for n, _, i in defs}
terms = re.findall(r'CEPH_FEATURE(MASK)?_(\w+)', allblk.group(1)) if allblk else []
all_names = [n for _, n in terms]
all_value = 0
for is_mask, n in terms:
    if n in names:
        all_value |= 1 << names[n]
        if is_mask:
            all_value |= inc[incs[n]]
    else:
        raise SystemExit(f"unknown feature in CEPH_FEATURES_ALL: {n}")
out = ["// Generated by tools/gen_features.py from ceph.git src/include/ceph_features.h; do not edit.",
       "//! Ceph connection feature bits (`CEPH_FEATURE_*`) and masks (`CEPH_FEATUREMASK_*`).", ""]
for n, b, i in defs:
    out.append(f"pub const {n}: u64 = 1 << {b};")
    out.append(f"pub const MASK_{n}: u64 = (1 << {b}) | 0x{inc[i]:x};")
out.append("")
out.append("/// `CEPH_FEATURES_ALL` at the reference commit.")
out.append(f"pub const ALL: u64 = 0x{all_value:x};")
out.append("")
out.append("/// `HAVE_FEATURE(features, NAME)`: all bits of the feature's mask are present.")
out.append("pub const fn has(features: u64, mask: u64) -> bool { features & mask == mask }")
open(sys.argv[2], "w").write("\n".join(out) + "\n")
print(f"{len(defs)} features, ALL has {len(all_names)} names, value 0x{all_value:x}")
