#!/usr/bin/env bash
# A small local Ceph cluster for the Rust MDS. One monitor, one manager, one
# memstore OSD, filesystem "a", and an mds.rust key. No C++ MDS is started.
#
#   devcluster/local-cluster.sh start [--build DIR] [--data DIR]
#   devcluster/local-cluster.sh stop  [--data DIR]
#   devcluster/local-cluster.sh status [--data DIR]
#
# The first start creates the cluster. Later starts only launch daemons that
# are down. Source the printed env file before ceph or ceph-rmds commands.
#
# With no MDS running, health stays HEALTH_ERR because filesystem a is
# offline. This Ceph build also reports ten missing manager modules.
# The OSD is memstore. stop sends SIGTERM so it can save. A SIGKILL drops
# the OSD objects.
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BUILD=""
DATA=/var/tmp/rust-mds-local
CMD=${1:-}
shift || true

while [ $# -gt 0 ]; do
    case $1 in
        --build) BUILD=${2:-}; shift 2 || { echo "ERROR: --build needs a directory" >&2; exit 1; } ;;
        --data) DATA=${2:-}; shift 2 || { echo "ERROR: --data needs a directory" >&2; exit 1; } ;;
        -h|--help) sed -n '2,15p' "$0"; exit 0 ;;
        *) echo "ERROR: unknown argument: $1" >&2; exit 1 ;;
    esac
done

CONF=$DATA/ceph.conf
ENV_FILE=$DATA/env.sh
LOG=$DATA/log
RUN=$DATA/run
KEYS=$DATA/keyring
FSID_FILE=$DATA/fsid
MON_IP=127.0.0.1
MON_V1=$MON_IP:6789
MON_V2=$MON_IP:3300
FS_NAME=a
META_POOL=cephfs.a.meta
DATA_POOL=cephfs.a.data

log() { echo "[local-cluster $(date +%T)] $*" >&2; }
die() { log "ERROR: $*"; exit 1; }

default_build() {
    if [ -n "${LOCAL_CEPH_BUILD:-}" ]; then
        echo "$LOCAL_CEPH_BUILD"
    elif [ -x "$REPO/../ceph/build/bin/ceph-mon" ]; then
        echo "$REPO/../ceph/build"
    else
        die "pass --build DIR (the directory that contains bin/ceph-mon)"
    fi
}

load_build() {
    [ -n "$BUILD" ] || BUILD=$(default_build)
    BUILD=$(cd "$BUILD" && pwd)
    BIN=$BUILD/bin
    LIB=$BUILD/lib
    [ -x "$BIN/ceph-mon" ] || die "no ceph-mon in $BIN"
    for tool in ceph ceph-mgr ceph-osd ceph-authtool monmaptool; do
        [ -x "$BIN/$tool" ] || die "missing $BIN/$tool"
    done
    local pybind cython
    pybind=$(cd "$BUILD/../src/pybind" && pwd)
    cython=$(compgen -G "$LIB/cython_modules/lib.*" | head -1 || true)
    [ -d "$cython" ] || die "no Python modules under $LIB/cython_modules"
    PYPATH=$pybind:$cython
}

with_libs() {
    # CEPH_LIB makes this build load its own plugins instead of /usr/local/lib/ceph.
    env LD_LIBRARY_PATH="$LIB${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}" \
        PYTHONPATH="$PYPATH${PYTHONPATH:+:$PYTHONPATH}" \
        CEPH_LIB="$LIB" \
        "$@"
}

c() { with_libs "$BIN/ceph" -c "$CONF" "$@"; }

pidfile() { echo "$RUN/$1.pid"; }

daemon_pid() {
    local f pid
    f=$(pidfile "$1")
    [ -f "$f" ] || return 0
    pid=$(cat "$f")
    if [ -n "$pid" ] && [ -r "/proc/$pid/cmdline" ] &&
        tr '\0' ' ' < "/proc/$pid/cmdline" | grep -q -- "$CONF"; then
        echo "$pid"
    fi
}

start_daemon() {
    local name=$1
    shift
    local pid
    pid=$(daemon_pid "$name")
    if [ -n "$pid" ]; then
        log "$name already running (pid $pid)"
        return 0
    fi
    mkdir -p "$LOG" "$RUN"
    setsid nohup env \
        LD_LIBRARY_PATH="$LIB${LD_LIBRARY_PATH:+:$LD_LIBRARY_PATH}" \
        PYTHONPATH="$PYPATH${PYTHONPATH:+:$PYTHONPATH}" \
        CEPH_LIB="$LIB" \
        "$@" >>"$LOG/$name.stdout" 2>&1 </dev/null &
    echo $! > "$(pidfile "$name")"
    sleep 0.5
    pid=$(daemon_pid "$name")
    [ -n "$pid" ] || die "$name failed to start; see $LOG/$name.stdout"
    log "started $name (pid $pid)"
}

stop_daemon() {
    local name=$1 pid i
    pid=$(daemon_pid "$name")
    if [ -z "$pid" ]; then
        rm -f "$(pidfile "$name")"
        return 0
    fi
    kill -TERM "$pid" 2>/dev/null || true
    for ((i = 0; i < 300; i++)); do
        kill -0 "$pid" 2>/dev/null || break
        sleep 0.1
    done
    if kill -0 "$pid" 2>/dev/null; then
        log "$name (pid $pid) did not exit; sending SIGKILL"
        kill -KILL "$pid" 2>/dev/null || true
        sleep 0.5
    fi
    rm -f "$(pidfile "$name")"
    log "stopped $name"
}

wait_until() {
    local seconds=$1 what=$2 i
    shift 2
    for ((i = 0; i < seconds; i++)); do
        if "$@" >/dev/null 2>&1; then return 0; fi
        sleep 1
    done
    die "timed out after ${seconds}s waiting for $what"
}

ports_free() {
    local port
    for port in 6789 3300; do
        if ss -ltn | grep -q ":$port "; then
            die "port $port is already in use"
        fi
    done
}

write_conf() {
    cat > "$CONF" <<EOF
# Generated by devcluster/local-cluster.sh. One monitor, one OSD, no MDS.
[global]
fsid = $FSID
mon_host = [v2:$MON_V2,v1:$MON_V1]
public_addr = $MON_IP
auth_cluster_required = cephx
auth_service_required = cephx
auth_client_required = cephx
ms_bind_msgr1 = true
ms_bind_msgr2 = true
ms_bind_port_min = 6800
ms_bind_port_max = 7300
mon_warn_on_insecure_global_id_reclaim = false
mon_warn_on_insecure_global_id_reclaim_allowed = false
keyring = $KEYS/\$cluster.\$name.keyring
run_dir = $RUN
crash_dir = $DATA/crash
osd_crush_chooseleaf_type = 0
osd_pool_default_size = 1
osd_pool_default_min_size = 1
osd_pool_default_pg_autoscale_mode = off
mon_max_pg_per_osd = 256
mon_allow_pool_delete = true
mon_allow_pool_size_one = true
mon_warn_on_pool_no_redundancy = false
mon_data_avail_warn = 10
mon_data_avail_crit = 5

[mon]
mon_data = $DATA/mon/\$id
keyring = \$mon_data/keyring
log_file = $LOG/\$cluster-\$name.log

[mgr]
mgr_data = $DATA/mgr/\$id
log_file = $LOG/\$cluster-\$name.log

[osd]
osd_data = $DATA/osd/\$id
keyring = \$osd_data/keyring
log_file = $LOG/\$cluster-\$name.log
osd_objectstore = memstore
memstore_device_bytes = 1073741824
osd_fast_shutdown = false

[mds.rust]
mds_join_fs = $FS_NAME
EOF
}

write_env() {
    cat > "$ENV_FILE" <<EOF
# Source this file:  source $ENV_FILE
export LOCAL_CEPH_BUILD=$BUILD
export PATH=$BIN:\$PATH
export LD_LIBRARY_PATH=$LIB\${LD_LIBRARY_PATH:+:\$LD_LIBRARY_PATH}
export CEPH_LIB=$LIB
export PYTHONPATH=$PYPATH\${PYTHONPATH:+:\$PYTHONPATH}
export CEPH_CONF=$CONF
export CEPH_KEYRING=$KEYS/ceph.client.admin.keyring
export CEPH_ADMIN_SECRET=$KEYS/client.admin.secret
export RMDS_KEYRING=$KEYS/ceph.mds.rust.keyring
export RMDS_NAME=rust
export MON_V1=$MON_V1
export MON_V2=$MON_V2
export CEPH_FS_NAME=$FS_NAME
EOF
}

create_keys() {
    mkdir -p "$KEYS"
    chmod 700 "$KEYS"
    "$BIN/ceph-authtool" --create-keyring "$KEYS/ceph.mon.keyring" --gen-key -n mon. --cap mon 'allow *' >/dev/null
    "$BIN/ceph-authtool" --create-keyring "$KEYS/ceph.client.admin.keyring" --gen-key -n client.admin \
        --cap mon 'allow *' --cap osd 'allow *' --cap mds 'allow *' --cap mgr 'allow *' >/dev/null
    "$BIN/ceph-authtool" --create-keyring "$KEYS/ceph.mgr.x.keyring" --gen-key -n mgr.x \
        --cap mon 'allow profile mgr' --cap osd 'allow *' --cap mds 'allow *' >/dev/null
    "$BIN/ceph-authtool" --create-keyring "$KEYS/ceph.mds.rust.keyring" --gen-key -n mds.rust \
        --cap mon 'allow profile mds' --cap osd 'allow rw tag cephfs *=*' \
        --cap mds 'allow' --cap mgr 'allow profile mds' >/dev/null
    "$BIN/ceph-authtool" "$KEYS/ceph.mon.keyring" --import-keyring "$KEYS/ceph.client.admin.keyring" >/dev/null
    "$BIN/ceph-authtool" "$KEYS/ceph.mon.keyring" --import-keyring "$KEYS/ceph.mgr.x.keyring" >/dev/null
    "$BIN/ceph-authtool" "$KEYS/ceph.mon.keyring" --import-keyring "$KEYS/ceph.mds.rust.keyring" >/dev/null
    "$BIN/ceph-authtool" -p -n client.admin "$KEYS/ceph.client.admin.keyring" > "$KEYS/client.admin.secret"
    chmod 600 "$KEYS"/*
}

create_osd() {
    local uuid secret got
    uuid=$(uuidgen)
    secret=$("$BIN/ceph-authtool" --gen-print-key)
    mkdir -p "$DATA/osd/0"
    printf '{"cephx_secret": "%s"}' "$secret" > "$DATA/osd/0/new.json"
    got=$(c osd new "$uuid" 0 -i "$DATA/osd/0/new.json")
    rm -f "$DATA/osd/0/new.json"
    [ "$got" = "0" ] || die "ceph osd new returned '$got'"
    with_libs "$BIN/ceph-osd" -c "$CONF" -i 0 --mkfs --key "$secret" --osd-uuid "$uuid" \
        > "$LOG/osd.0.mkfs.log" 2>&1 || die "osd mkfs failed; see $LOG/osd.0.mkfs.log"
    printf '[osd.0]\n\tkey = %s\n' "$secret" > "$DATA/osd/0/keyring"
    chmod 600 "$DATA/osd/0/keyring"
}

create_cluster() {
    if [ -e "$DATA" ] && [ -n "$(ls -A "$DATA" 2>/dev/null)" ]; then
        die "$DATA is not empty; remove it or pass another --data directory"
    fi
    command -v uuidgen >/dev/null || die "uuidgen is not installed"
    ports_free
    log "creating a cluster in $DATA"
    mkdir -p "$DATA"/{log,run,crash,mon/a,mgr/x}
    FSID=$(uuidgen)
    echo "$FSID" > "$FSID_FILE"
    echo "$BUILD" > "$DATA/build"
    write_conf
    create_keys
    with_libs "$BIN/monmaptool" --create --clobber --fsid "$FSID" \
        --addv a "[v2:$MON_V2,v1:$MON_V1]" "$DATA/monmap" >/dev/null
    with_libs "$BIN/ceph-mon" -c "$CONF" --mkfs -i a --monmap "$DATA/monmap" \
        --keyring "$KEYS/ceph.mon.keyring" > "$LOG/mon.a.mkfs.log" 2>&1 \
        || die "mon mkfs failed; see $LOG/mon.a.mkfs.log"
    start_daemon mon.a "$BIN/ceph-mon" -f -c "$CONF" -i a
    wait_until 60 "monitor quorum" c quorum_status
    create_osd
    touch "$DATA/osds-created"
}

osd_up() {
    # ceph --format json prints "num_up_osds":1 with no space after the colon.
    c osd stat --format json | python3 -c '
import json, sys
d = json.load(sys.stdin)
sys.exit(0 if d.get("num_up_osds") == 1 else 1)
'
}

pgs_active() {
    c pg stat --format json | python3 -c '
import json, sys
d = json.load(sys.stdin)
d = d.get("pg_summary", d)
total = d.get("num_pgs", 0)
active = sum(s["num"] for s in d.get("num_pg_by_state", []) if str(s["name"]).startswith("active"))
sys.exit(0 if total and active == total else 1)
'
}

start_cluster() {
    load_build
    mkdir -p "$DATA"
    if [ ! -f "$DATA/osds-created" ]; then
        create_cluster
    else
        BUILD=$(cat "$DATA/build")
        load_build
        FSID=$(cat "$FSID_FILE")
    fi
    start_daemon mon.a "$BIN/ceph-mon" -f -c "$CONF" -i a
    wait_until 60 "monitor quorum" c quorum_status
    start_daemon mgr.x "$BIN/ceph-mgr" -f -c "$CONF" -i x
    start_daemon osd.0 "$BIN/ceph-osd" -f -c "$CONF" -i 0
    wait_until 120 "OSD 0 up" osd_up
    if [ ! -f "$DATA/created" ]; then
        log "creating filesystem $FS_NAME"
        c osd pool create "$META_POOL" 8 8 replicated >/dev/null
        c osd pool create "$DATA_POOL" 8 8 replicated >/dev/null
        c fs new "$FS_NAME" "$META_POOL" "$DATA_POOL" >/dev/null
        date -Is > "$DATA/created"
    fi
    wait_until 180 "PGs active" pgs_active
    write_env
    log "filesystem $FS_NAME is ready and has no MDS"
    log "source $ENV_FILE"
}

stop_cluster() {
    [ -f "$DATA/build" ] || die "no cluster in $DATA"
    BUILD=$(cat "$DATA/build")
    load_build
    stop_daemon osd.0
    stop_daemon mgr.x
    stop_daemon mon.a
}

status_cluster() {
    [ -f "$CONF" ] || die "no cluster in $DATA"
    BUILD=$(cat "$DATA/build")
    load_build
    with_libs "$BIN/ceph" -c "$CONF" -s || true
    echo
    with_libs "$BIN/ceph" -c "$CONF" fs dump || true
}

case $CMD in
    start) start_cluster ;;
    stop) stop_cluster ;;
    status) status_cluster ;;
    *) sed -n '2,12p' "$0"; exit 2 ;;
esac
