#!/usr/bin/env bash
# Start the single-node dev cluster (creating it first if it does not exist).
#
#   start.sh [--mds none|cpp|cpp-v1]
#
#   --mds none    (default) start no MDS, so a Rust MDS (mds.rust) can take rank 0.
#                 Stops the C++ MDS if it is running.
#   --mds cpp     also start the C++ MDS "mds.a" (msgr2 + msgr1, ports 7400/7401).
#   --mds cpp-v1  C++ MDS bound to msgr1 only (ms_bind_msgr2=false, v1 port 7401);
#                 it then also talks msgr1 to the monitor.
#
# Idempotent: daemons that are already running are left alone.
set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/common.sh"

MDS_MODE=none
while [ $# -gt 0 ]; do
    case $1 in
        --mds) MDS_MODE=${2:-}; shift 2 || die "--mds needs a value" ;;
        --mds=*) MDS_MODE=${1#--mds=}; shift ;;
        -h|--help) sed -n '2,13p' "$0"; exit 0 ;;
        *) die "unknown argument: $1 (see --help)" ;;
    esac
done
case $MDS_MODE in none|cpp|cpp-v1) ;; *) die "--mds must be none, cpp or cpp-v1" ;; esac

write_conf() {
    cat > "$CONF" <<EOF
# Generated by rust-mds/devcluster/start.sh on $(date -Is). Single-node dev cluster.
# Edit with care: start.sh only writes this file when it creates the cluster.
[global]
fsid = $FSID
mon_host = [v2:$MON_V2,v1:$MON_V1]
public_addr = $MON_IP
cluster_addr = $MON_IP
# Both protocols on every daemon. The Rust MDS uses msgr1 (v1) only.
ms_bind_msgr1 = true
ms_bind_msgr2 = true
# Random daemon ports come from this range; 7400-7499 is kept free for MDS daemons.
ms_bind_port_min = 6800
ms_bind_port_max = 7300

auth_cluster_required = cephx
auth_service_required = cephx
auth_client_required = cephx
# Dev convenience: do not warn about (still allowed) insecure global_id reclaim.
mon_warn_on_insecure_global_id_reclaim = false
mon_warn_on_insecure_global_id_reclaim_allowed = false

keyring = $KEYRING_DIR/\$cluster.\$name.keyring
run_dir = $RUN_DIR
crash_dir = $DATA/crash

# 3 OSDs on one host: replicate across OSDs (CRUSH failure domain = osd), size 3.
osd_crush_chooseleaf_type = 0
osd_pool_default_size = 3
osd_pool_default_min_size = 2
osd_pool_default_pg_num = $PG_NUM
osd_pool_default_pgp_num = $PG_NUM
osd_pool_default_pg_autoscale_mode = off
mon_max_pg_per_osd = 1000
mon_allow_pool_delete = true
mon_allow_pool_size_one = true

[mon]
mon_data = $DATA/mon/\$id
keyring = \$mon_data/keyring
log_file = $LOG_DIR/\$cluster-\$name.log
mon_cluster_log_file = default=$LOG_DIR/\$cluster.\$channel.log cluster=$LOG_DIR/\$cluster.log
# Verbose on purpose: shows why beacons/auth from a new MDS are accepted or not.
debug_mon = 10
debug_auth = 10
debug_ms = 1

[mgr]
mgr_data = $DATA/mgr/\$id
log_file = $LOG_DIR/\$cluster-\$name.log

[osd]
osd_data = $DATA/osd/\$id
keyring = \$osd_data/keyring
log_file = $LOG_DIR/\$cluster-\$name.log
osd_objectstore = memstore
memstore_device_bytes = 4294967296
# memstore keeps objects in RAM and writes them to osd_data only on umount; the
# default fast shutdown path _exit()s without umount, losing everything.
osd_fast_shutdown = false

[mds]
mds_data = $DATA/mds/\$id
log_file = $LOG_DIR/\$cluster-\$name.log

[mds.$CPP_MDS_ID]
# The C++ reference MDS: fixed ports v2 $CPP_MDS_PORT_V2, v1 $CPP_MDS_PORT_V1.
ms_bind_port_min = $CPP_MDS_PORT_V2
ms_bind_port_max = $CPP_MDS_PORT_V1
debug_mds = 10
debug_ms = 1
EOF
}

create_keys() {
    mkdir -p "$KEYRING_DIR"
    chmod 700 "$KEYRING_DIR"
    ceph-authtool --create-keyring "$MON_KEYRING" --gen-key -n mon. --cap mon 'allow *' >/dev/null
    ceph-authtool --create-keyring "$ADMIN_KEYRING" --gen-key -n client.admin \
        --cap mon 'allow *' --cap osd 'allow *' --cap mds 'allow *' --cap mgr 'allow *' >/dev/null
    ceph-authtool --create-keyring "$MGR_KEYRING" --gen-key -n mgr.$MGR_ID \
        --cap mon 'allow profile mgr' --cap osd 'allow *' --cap mds 'allow *' >/dev/null
    local id kr
    for id in $CPP_MDS_ID $RUST_MDS_ID; do
        kr=$KEYRING_DIR/ceph.mds.$id.keyring
        ceph-authtool --create-keyring "$kr" --gen-key -n mds.$id \
            --cap "${MDS_CAPS[0]}" "${MDS_CAPS[1]}" --cap "${MDS_CAPS[2]}" "${MDS_CAPS[3]}" \
            --cap "${MDS_CAPS[4]}" "${MDS_CAPS[5]}" --cap "${MDS_CAPS[6]}" "${MDS_CAPS[7]}" >/dev/null
    done
    for kr in "$ADMIN_KEYRING" "$MGR_KEYRING" "$CPP_MDS_KEYRING" "$RMDS_KEYRING"; do
        ceph-authtool "$MON_KEYRING" --import-keyring "$kr" >/dev/null
    done
    ceph-authtool -p -n client.admin "$ADMIN_KEYRING" > "$ADMIN_SECRET"
    chmod 600 "$KEYRING_DIR"/*
}

create_osd() {
    local id=$1 uuid secret got
    uuid=$(uuidgen)
    secret=$(ceph-authtool --gen-print-key)
    mkdir -p "$DATA/osd/$id"
    printf '{"cephx_secret": "%s"}' "$secret" > "$DATA/osd/$id/new.json"
    got=$(c osd new "$uuid" "$id" -i "$DATA/osd/$id/new.json")
    rm -f "$DATA/osd/$id/new.json"
    [ "$got" = "$id" ] || die "ceph osd new returned '$got', expected $id"
    ceph-osd -c "$CONF" -i "$id" --mkfs --key "$secret" --osd-uuid "$uuid" \
        > "$LOG_DIR/osd.$id.mkfs.log" 2>&1 || die "osd.$id mkfs failed, see $LOG_DIR/osd.$id.mkfs.log"
    [ -f "$DATA/osd/$id/type" ] || die "osd.$id mkfs wrote no type file"
    printf '[osd.%s]\n\tkey = %s\n' "$id" "$secret" > "$DATA/osd/$id/keyring"
    chmod 600 "$DATA/osd/$id/keyring"
}

create_cluster() {
    [ -e "$DATA" ] && [ -n "$(ls -A "$DATA" 2>/dev/null)" ] &&
        die "$DATA exists but is not a complete cluster; run reset.sh first"
    log "creating a new cluster in $DATA"
    mkdir -p "$DATA"/{log,run,crash,mon/$MON_ID,mgr/$MGR_ID,mds/$CPP_MDS_ID,mds/$RUST_MDS_ID}
    FSID=$(uuidgen)
    echo "$FSID" > "$DATA/fsid"
    write_conf
    create_keys
    monmaptool --create --clobber --fsid "$FSID" --addv $MON_ID "[v2:$MON_V2,v1:$MON_V1]" \
        --enable-all-features "$DATA/monmap" >/dev/null
    ceph-mon -c "$CONF" --mkfs -i $MON_ID --monmap "$DATA/monmap" --keyring "$MON_KEYRING" \
        > "$LOG_DIR/mon.$MON_ID.mkfs.log" 2>&1 || die "mon mkfs failed, see $LOG_DIR/mon.$MON_ID.mkfs.log"
    start_mon
    for id in "${OSD_IDS[@]}"; do create_osd "$id"; done
    touch "$DATA/osds-created"
}

start_mon() {
    start_daemon mon.$MON_ID ceph-mon -f -c "$CONF" -i $MON_ID
    wait_until 60 "monitor quorum" c quorum_status
}

mds_running_mode() {   # prints cpp, cpp-v1 or nothing
    local pid
    pid=$(daemon_pid mds.$CPP_MDS_ID)
    [ -n "$pid" ] || return 0
    if tr '\0' ' ' < "/proc/$pid/cmdline" | grep -q -- '--ms_bind_msgr2=false'; then
        echo cpp-v1
    else
        echo cpp
    fi
}

fs_rank0_state() {   # e.g. up:active, or "none"
    c fs get $FS_NAME --format json 2>/dev/null | python3 -c '
import json, sys
m = json.load(sys.stdin)["mdsmap"]
for info in m.get("info", {}).values():
    if info.get("rank") == 0:
        print(info["state"], info["name"]); break
else:
    print("none", "failed" if 0 in m.get("failed", []) else "")'
}

all_pgs_active() {
    c pg stat --format json | python3 -c '
import json, sys
d = json.load(sys.stdin)
d = d.get("pg_summary", d)
total = d.get("num_pgs", 0)
active = sum(s["num"] for s in d.get("num_pg_by_state", []) if s["name"].startswith("active"))
sys.exit(0 if total > 0 and active == total else 1)'
}

all_osds_up() {
    local n
    n=$(c osd stat --format json | python3 -c 'import json, sys; print(json.load(sys.stdin)["num_up_osds"])')
    [ "$n" = "${#OSD_IDS[@]}" ]
}

cpp_mds_active() { [ "$(fs_rank0_state)" = "up:active $CPP_MDS_ID" ]; }

# --- main -----------------------------------------------------------------
command -v ceph-mon >/dev/null || die "ceph packages are not installed"
mkdir -p "$DATA"

[ -f "$DATA/osds-created" ] || create_cluster
FSID=$(cat "$DATA/fsid")
build_gctx_shim || log "warning: could not build $GCTX_SHIM (gcc missing?)"

start_mon
start_daemon mgr.$MGR_ID ceph-mgr -f -c "$CONF" -i $MGR_ID
for id in "${OSD_IDS[@]}"; do
    start_daemon osd.$id ceph-osd -f -c "$CONF" -i "$id"
done
wait_until 120 "all ${#OSD_IDS[@]} OSDs up" all_osds_up

if ! cluster_exists; then
    log "creating pools $META_POOL, $DATA_POOL and file system $FS_NAME"
    c osd pool create $META_POOL $PG_NUM $PG_NUM replicated >/dev/null
    c osd pool create $DATA_POOL $PG_NUM $PG_NUM replicated >/dev/null
    c fs new $FS_NAME $META_POOL $DATA_POOL >/dev/null
    date -Is > "$DATA/created"
fi
wait_until 180 "all PGs active" all_pgs_active

case $MDS_MODE in
    none)
        if [ -n "$(daemon_pid mds.$CPP_MDS_ID)" ]; then
            stop_daemon mds.$CPP_MDS_ID
        fi
        ;;
    cpp|cpp-v1)
        cur=$(mds_running_mode)
        if [ -n "$cur" ] && [ "$cur" != "$MDS_MODE" ]; then
            log "C++ MDS is running in mode $cur, restarting it in mode $MDS_MODE"
            stop_daemon mds.$CPP_MDS_ID
        fi
        if [ "$MDS_MODE" = cpp ]; then
            start_daemon mds.$CPP_MDS_ID ceph-mds -f -c "$CONF" -i $CPP_MDS_ID
        else
            start_daemon mds.$CPP_MDS_ID ceph-mds -f -c "$CONF" -i $CPP_MDS_ID \
                --ms_bind_msgr2=false --public_addr=$MON_IP:$CPP_MDS_PORT_V1
        fi
        wait_until 90 "mds.$CPP_MDS_ID to hold rank 0 of $FS_NAME in up:active" cpp_mds_active
        ;;
esac

r0=$(fs_rank0_state || true)
log "cluster $FSID is up; fs $FS_NAME rank 0: ${r0:-unknown}"
if [ "$MDS_MODE" = none ]; then
    case $r0 in
        "none failed"*) log "note: rank 0 is failed (an MDS held it before); the next MDS gets up:replay. Run newfs.sh for a fresh fs (up:creating)." ;;
        "none"*) log "no MDS holds rank 0; the first MDS to beacon will be told up:creating" ;;
    esac
fi
log "use: source $DEVCLUSTER_DIR/env.sh   (CEPH_CONF=$CONF)"
