#!/usr/bin/env bash
# NFS-Ganesha with an FSAL_CEPH export of file system "a" (as client.admin),
# NFSv4.1/4.2 only, on 127.0.0.1:12049 (the packaged system service, if running,
# keeps 2049).
#
#   ganesha.sh start|stop|status|print-config|run [smoke|recovery]
# recovery keeps an on-disk NFSv4 recovery directory and enables 90s grace.
#
# Mount:  sudo mount -t nfs -o vers=4.1,port=12049 127.0.0.1:/a <mountpoint>
# Log:    $DATA/log/ganesha.log    Config: $DATA/ganesha/ganesha.conf
set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/common.sh"

ACTION=${1:-}
MODE=${2:-smoke}
[[ $# -le 2 ]] || die "usage: $0 start|stop|status|print-config|run [smoke|recovery]"
case $MODE in smoke|recovery) ;; *) die "mode must be smoke or recovery" ;; esac
GDIR=$DATA/ganesha
GRACELESS=true
if [[ $MODE == recovery ]]; then
    GDIR=$DATA/ganesha-recovery
    GRACELESS=false
fi
GCONF=$GDIR/ganesha.conf
GPORT=12049
GPID=$GDIR/ganesha.pid
GNODE=rust-mds-devcluster

ganesha_pid() {
    local pid
    pid=$(cat "$GPID" 2>/dev/null || true)
    if [ -n "$pid" ] && tr '\0' ' ' < "/proc/$pid/cmdline" 2>/dev/null | grep -q -- "$GCONF"; then
        echo "$pid"
    fi
}

print_conf() {
    local fsid
    if [[ $ACTION == print-config && -n ${GANESHA_CONFIG_FSID:-} ]]; then
        fsid=$GANESHA_CONFIG_FSID
    else
        fsid=$(cat "$DATA/fsid")
    fi
    [[ $fsid =~ ^[[:xdigit:]]{8}-[[:xdigit:]]{4}-[[:xdigit:]]{4}-[[:xdigit:]]{4}-[[:xdigit:]]{12}$ ]] || die "invalid cluster fsid"
    local scope="rust-mds-devcluster-$fsid"
    cat <<EOF
# Generated by devcluster/ganesha.sh; mode=$MODE
NFS_CORE_PARAM {
    Protocols = 4;
    NFS_Port = $GPORT;
    Bind_addr = 127.0.0.1;
    Enable_NLM = false;
    Enable_RQUOTA = false;
    # Ganesha runs as the normal user, which may not set PR_SET_IO_FLUSHER.
    allow_set_io_flusher_fail = true;
}
NFS_KRB5 {
    Active_krb5 = false;
}
NFSv4 {
    RecoveryBackend = fs;
    RecoveryRoot = $GDIR/recov;
    Minor_Versions = 1, 2;
    Graceless = $GRACELESS;
    Grace_Period = 90;
    Lease_Lifetime = 60;
    Delegations = false;
    Server_Owner = "$scope";
    Server_Scope = "$scope";
}
MDCACHE {
    Dir_Chunk = 0;
}
EXPORT {
    Export_ID = 100;
    Protocols = 4;
    Transports = TCP;
    Path = /;
    Pseudo = /$FS_NAME;
    Access_Type = RW;
    Squash = No_Root_Squash;
    Attr_Expiration_Time = 0;
    FSAL {
        Name = CEPH;
        User_Id = admin;
        Filesystem = $FS_NAME;
    }
}
    CEPH {
    Ceph_Conf = $CONF;
    client_oc = false;
}
LOG {
    Default_Log_Level = EVENT;
}
EOF
}

case $ACTION in
    print-config)
        print_conf
        ;;
    run)
        # The G3 controller owns this foreground process directly. Never use
        # the PID-file stop path to select a system or pre-existing helper.
        [[ $MODE == recovery ]] || die "foreground controller mode requires recovery"
        cluster_exists || die "no existing cluster"
        [[ -r $GCTX_SHIM ]] || die "existing gctx shim required; no automatic build"
        [[ ! -L $GDIR && ! -L $GDIR/recov && ! -L $GCONF ]] || die "recovery paths must not be symlinks"
        for other in "$DATA/ganesha" "$DATA/ganesha-recovery"; do
            other_pid=$(cat "$other/ganesha.pid" 2>/dev/null || true)
            if [[ -n $other_pid && -r /proc/$other_pid/cmdline ]] &&
                tr '\0' ' ' <"/proc/$other_pid/cmdline" | grep -qF -- "$other/ganesha.conf"; then
                die "existing helper is not controller-owned"
            fi
        done
        mkdir -p "$GDIR/recov"
        expected=$(print_conf)
        if [[ -e $GCONF ]]; then
            [[ $(cat "$GCONF") == "$expected" ]] || die "existing recovery config differs; preserve it"
        else
            printf '%s\n' "$expected" > "$GCONF"
        fi
        exec env LD_PRELOAD="$GCTX_SHIM" ganesha.nfsd -I "$GNODE" -F -f "$GCONF" \
            -L "$LOG_DIR/ganesha-recovery.log" -p "$GPID" -N NIV_EVENT
        ;;
    start)
        cluster_exists || die "no cluster (run start.sh)"
        if [ -n "$(ganesha_pid)" ]; then log "ganesha already running (pid $(ganesha_pid))"; exit 0; fi
        for other in "$DATA/ganesha" "$DATA/ganesha-recovery"; do
            [[ $other == "$GDIR" ]] && continue
            other_pid=$(cat "$other/ganesha.pid" 2>/dev/null || true)
            if [[ -n $other_pid && -r /proc/$other_pid/cmdline ]] &&
                tr '\0' ' ' <"/proc/$other_pid/cmdline" | grep -qF -- "$other/ganesha.conf"; then
                die "other helper mode is running; stop it explicitly before changing mode"
            fi
        done
        mkdir -p "$GDIR/recov"
        print_conf > "$GCONF"
        build_gctx_shim
        LD_PRELOAD=$GCTX_SHIM setsid nohup ganesha.nfsd -I "$GNODE" -F -f "$GCONF" -L "$LOG_DIR/ganesha.log" -p "$GPID" -N NIV_EVENT \
            >>"$LOG_DIR/ganesha.stdout" 2>&1 </dev/null &
        pid=$!
        echo $pid > "$GPID"
        for _ in $(seq 30); do
            kill -0 $pid 2>/dev/null || die "ganesha exited; see $LOG_DIR/ganesha.log"
            if (exec 3<>/dev/tcp/127.0.0.1/$GPORT) 2>/dev/null; then
                log "ganesha running (pid $(ganesha_pid)), export 127.0.0.1:/$FS_NAME on port $GPORT"
                [[ $MODE != recovery ]] || log "recovery mode: stable node $GNODE; 90s grace, 60s lease; retain $GDIR/recov across restarts"
                log "mount: sudo mount -t nfs -o vers=4.1,port=$GPORT 127.0.0.1:/$FS_NAME <mountpoint>"
                exit 0
            fi
            sleep 1
        done
        die "ganesha does not listen on $GPORT; see $LOG_DIR/ganesha.log"
        ;;
    stop)
        pid=$(ganesha_pid)
        if [ -z "$pid" ]; then log "ganesha not running"; exit 0; fi
        kill -TERM "$pid"
        for _ in $(seq 30); do kill -0 "$pid" 2>/dev/null || break; sleep 1; done
        kill -KILL "$pid" 2>/dev/null || true
        rm -f "$GPID"
        log "ganesha stopped"
        ;;
    status)
        pid=$(ganesha_pid)
        if [ -n "$pid" ]; then echo "ganesha running (pid $pid), port $GPORT"; else echo "ganesha not running"; fi
        ;;
    *) die "usage: $0 start|stop|status|print-config|run [smoke|recovery]" ;;
esac
