#!/usr/bin/env bash
# NFS-Ganesha with an FSAL_CEPH export of file system "a" (as client.admin),
# NFSv4.1/4.2 only, on 127.0.0.1:12049 (the packaged system service, if running,
# keeps 2049).
#
#   ganesha.sh start|stop|status
#
# Mount:  sudo mount -t nfs -o vers=4.1,port=12049 127.0.0.1:/a <mountpoint>
# Log:    $DATA/log/ganesha.log    Config: $DATA/ganesha/ganesha.conf
set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/common.sh"

GDIR=$DATA/ganesha
GCONF=$GDIR/ganesha.conf
GPORT=12049
GPID=$GDIR/ganesha.pid

ganesha_pid() {
    local pid
    pid=$(cat "$GPID" 2>/dev/null || true)
    if [ -n "$pid" ] && tr '\0' ' ' < "/proc/$pid/cmdline" 2>/dev/null | grep -q -- "$GCONF"; then
        echo "$pid"
    fi
}

write_conf() {
    mkdir -p "$GDIR/recov"
    cat > "$GCONF" <<EOF
# Generated by devcluster/ganesha.sh
NFS_CORE_PARAM {
    Protocols = 4;
    NFS_Port = $GPORT;
    Bind_addr = 127.0.0.1;
    Enable_NLM = false;
    Enable_RQUOTA = false;
    # Ganesha runs as the normal user, which may not set PR_SET_IO_FLUSHER.
    allow_set_io_flusher_fail = true;
}
NFS_KRB5 {
    Active_krb5 = false;
}
NFSv4 {
    RecoveryBackend = fs;
    RecoveryRoot = $GDIR/recov;
    Minor_Versions = 1, 2;
    Graceless = true;
}
MDCACHE {
    Dir_Chunk = 0;
}
EXPORT {
    Export_ID = 100;
    Protocols = 4;
    Transports = TCP;
    Path = /;
    Pseudo = /$FS_NAME;
    Access_Type = RW;
    Squash = No_Root_Squash;
    Attr_Expiration_Time = 0;
    FSAL {
        Name = CEPH;
        User_Id = admin;
        Filesystem = $FS_NAME;
    }
}
CEPH {
    Ceph_Conf = $CONF;
}
LOG {
    Default_Log_Level = EVENT;
}
EOF
}

case ${1:-} in
    start)
        cluster_exists || die "no cluster (run start.sh)"
        if [ -n "$(ganesha_pid)" ]; then log "ganesha already running (pid $(ganesha_pid))"; exit 0; fi
        write_conf
        build_gctx_shim
        LD_PRELOAD=$GCTX_SHIM setsid nohup ganesha.nfsd -F -f "$GCONF" -L "$LOG_DIR/ganesha.log" -p "$GPID" -N NIV_EVENT \
            >>"$LOG_DIR/ganesha.stdout" 2>&1 </dev/null &
        pid=$!
        echo $pid > "$GPID"
        for _ in $(seq 30); do
            kill -0 $pid 2>/dev/null || die "ganesha exited; see $LOG_DIR/ganesha.log"
            if (exec 3<>/dev/tcp/127.0.0.1/$GPORT) 2>/dev/null; then
                log "ganesha running (pid $(ganesha_pid)), export 127.0.0.1:/$FS_NAME on port $GPORT"
                log "mount: sudo mount -t nfs -o vers=4.1,port=$GPORT 127.0.0.1:/$FS_NAME <mountpoint>"
                exit 0
            fi
            sleep 1
        done
        die "ganesha does not listen on $GPORT; see $LOG_DIR/ganesha.log"
        ;;
    stop)
        pid=$(ganesha_pid)
        if [ -z "$pid" ]; then log "ganesha not running"; exit 0; fi
        kill -TERM "$pid"
        for _ in $(seq 30); do kill -0 "$pid" 2>/dev/null || break; sleep 1; done
        kill -KILL "$pid" 2>/dev/null || true
        rm -f "$GPID"
        log "ganesha stopped"
        ;;
    status)
        pid=$(ganesha_pid)
        if [ -n "$pid" ]; then echo "ganesha running (pid $pid), port $GPORT"; else echo "ganesha not running"; fi
        ;;
    *) die "usage: $0 start|stop|status" ;;
esac
